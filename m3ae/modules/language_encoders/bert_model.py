def apply_chunking_to_forward(forward_fn, chunk_size, chunk_dim, *inputs):
    if chunk_size is None or chunk_size == 0:
        return forward_fn(*inputs)
    
    tensor_inputs = [i for i in inputs if isinstance(i, torch.Tensor)]
    if not tensor_inputs:
        return forward_fn(*inputs)
    
    seq_len = tensor_inputs[0].size(chunk_dim)
    if seq_len <= chunk_size:
        return forward_fn(*inputs)
    
    outputs = []
    for i in range(0, seq_len, chunk_size):
        chunked_inputs = [
            torch.narrow(arg, chunk_dim, i, min(chunk_size, seq_len - i)) if isinstance(arg, torch.Tensor) else arg
            for arg in inputs
        ]
        out = forward_fn(*chunked_inputs)
        outputs.append(out)
        
    if isinstance(outputs[0], tuple):
        return tuple(torch.cat([o[idx] for o in outputs], dim=chunk_dim) for idx in range(len(outputs[0])))
    return torch.cat(outputs, dim=chunk_dim)
	
