class GAT_module(nn.Module):
    def __init__(self, feature_size, head=8):
        super().__init__()
        self.cross_attn_kw = cross_attention(head=head, feature_size=feature_size)
        self.ffd = poswise_ffd(feature_size)
        GAT_head = 4
        self.GAN_layer = GAT(
            nfeat=feature_size,
            nhid=feature_size // GAT_head,
            nclass=feature_size,
            dropout=0.2,
            alpha=0.2,
            nheads=GAT_head
        )
        self.cross_attn_kw.apply(init_weights)
        self.ffd.apply(init_weights)

    def forward(self, x, organ_disease_feature, adj):
        knowledge_feat = self.GAN_layer(organ_disease_feature, adj)
        k_prime = self.cross_attn_kw(knowledge_feat, x, x)
        return self.ffd(k_prime)


class BertCrossLayer(nn.Module):
    def __init__(self, config):
        super().__init__()
        self.chunk_size_feed_forward = getattr(config, 'chunk_size_feed_forward', 0)
        self.seq_len_dim = 1
        self.attention = BertAttention(config)
        self.is_decoder = config.is_decoder
        self.add_cross_attention = config.add_cross_attention
        self.crossattention = BertAttention(config)
        self.intermediate = BertIntermediate(config)
        self.output = BertOutput(config)

    def forward(
            self,
            hidden_states,
            encoder_hidden_states,
            attention_mask=None,
            encoder_attention_mask=None,
            output_attentions=False,
    ):
        self_attention_outputs = self.attention(
            hidden_states,
            attention_mask,
            head_mask=None,
            output_attentions=output_attentions,
            past_key_value=None,
        )
        attention_output = self_attention_outputs[0]
        outputs = self_attention_outputs[1:]

        cross_attention_outputs = self.crossattention(
            attention_output,
            attention_mask,
            None,
            encoder_hidden_states,
            encoder_attention_mask,
            None,
            output_attentions,
        )
        attention_output = cross_attention_outputs[0]
        outputs = outputs + cross_attention_outputs[1:]

        layer_output = apply_chunking_to_forward(
            self.feed_forward_chunk, self.chunk_size_feed_forward, self.seq_len_dim, attention_output
        )
        outputs = (layer_output,) + outputs
        return outputs

    def feed_forward_chunk(self, attention_output):
        return self.output(self.intermediate(attention_output), attention_output)


